import React, { useState, useEffect, useRef, Suspense } from 'react';
import JourneyProgress from '@/components/JourneyProgress';
import { useSearchParams } from 'next/navigation';

// Child component that reads the URL param — must be inside <Suspense>
function TopicAutoFill({ onTopic }: { onTopic: (t: string) => void }) {
  const searchParams = useSearchParams();
  useEffect(() => {
    const t = searchParams.get('topic');
    if (t && t.trim().length > 0) onTopic(t.trim());
  }, [searchParams, onTopic]);
  return null;
}

import Link from 'next/link';
import { supabase } from '@/lib/supabase/client';
import SiteHeader from '@/components/SiteHeader';
import ScoreCircle from '@/components/ScoreCircle';

interface AnalysisData {
  clarityScore: number;
  feasibilityScore: number;
  applicabilityScore: number;
  diagnosis: string;
  reportScore: number;
}

interface ApiResponse {
  success: boolean;
  error?: string;
  data?: AnalysisData;
  papers?: Paper[];
  saved?: boolean;
}

interface Paper { title: string; year: number | null; citationCount: number; url: string | null }

const FREE_ATTEMPTS = 3;
const ATTEMPTS_KEY = 'waha_anon_attempts';
const LANG_KEY = 'waha_lang';

