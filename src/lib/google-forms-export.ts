export type QuestionnaireItemKind = 'likert5' | 'single_choice' | 'multiple_choice' | 'short_text' | 'long_text';

export type QuestionnaireItem = {
  text: string;
  kind: QuestionnaireItemKind;
  required: boolean;
  options: string[];
};

export type QuestionnaireField = {
  label: string;
  kind: 'short_text' | 'single_choice';
  required: boolean;
  options: string[];
};

export type QuestionnaireSection = {
  title: string;
  variableName: string;
  description: string;
  items: QuestionnaireItem[];
};

export type Questionnaire = {
  title: string;
  description: string;
  consentStatement: string;
  instructions: string;
  respondentFields: QuestionnaireField[];
  sections: QuestionnaireSection[];
};

const value = (input: string) => JSON.stringify(input.trim());
const options = (input: string[]) => JSON.stringify(input.map((item) => item.trim()).filter(Boolean));

function itemScript(item: QuestionnaireItem) {
  const title = value(item.text);
  const required = item.required ? 'true' : 'false';
  if (item.kind === 'likert5') return `  form.addScaleItem().setTitle(${title}).setBounds(1, 5).setLabels('لا أوافق بشدة', 'أوافق بشدة').setRequired(${required});`;
  if (item.kind === 'multiple_choice') return `  form.addCheckboxItem().setTitle(${title}).setChoiceValues(${options(item.options)}).setRequired(${required});`;
  if (item.kind === 'single_choice') return `  form.addMultipleChoiceItem().setTitle(${title}).setChoiceValues(${options(item.options)}).setRequired(${required});`;
  if (item.kind === 'long_text') return `  form.addParagraphTextItem().setTitle(${title}).setRequired(${required});`;
  return `  form.addTextItem().setTitle(${title}).setRequired(${required});`;
}

export function createGoogleFormsScript(questionnaire: Questionnaire) {
  const lines = [
    '/**',
    ' * Generated by WAHA from the approved questionnaire draft.',
    ' * Review the instrument, obtain expert review/ethics approval when required, then run this function at script.google.com.',
    ' */',
    'function createWahaQuestionnaire() {',
    `  const form = FormApp.create(${value(questionnaire.title)}, true);`,
    `  form.setDescription(${value(`${questionnaire.description}\n\n${questionnaire.instructions}`)});`,
    `  form.addSectionHeaderItem().setTitle('الموافقة على المشاركة').setHelpText(${value(questionnaire.consentStatement)});`,
    "  form.addMultipleChoiceItem().setTitle('هل توافق على المشاركة بعد قراءة المعلومات أعلاه؟').setChoiceValues(['نعم، أوافق', 'لا، لا أوافق']).setRequired(true);",
  ];
  for (const field of questionnaire.respondentFields) {
    if (field.kind === 'single_choice') lines.push(`  form.addMultipleChoiceItem().setTitle(${value(field.label)}).setChoiceValues(${options(field.options)}).setRequired(${field.required ? 'true' : 'false'});`);
    else lines.push(`  form.addTextItem().setTitle(${value(field.label)}).setRequired(${field.required ? 'true' : 'false'});`);
  }
  questionnaire.sections.forEach((section, index) => {
    lines.push(`  form.addPageBreakItem().setTitle(${value(`${index + 1}. ${section.title}`)}).setHelpText(${value(section.description)});`);
    section.items.forEach((item) => lines.push(itemScript(item)));
  });
  lines.push("  Logger.log('رابط التعديل: ' + form.getEditUrl());", "  Logger.log('رابط المشاركة: ' + form.getPublishedUrl());", '}');
  return `${lines.join('\n')}\n`;
}
