import { mkdtempSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';
import { attachWritingSource } from '@/lib/evidence-writing';
import { bibliographyFromReference } from '@/lib/citations/writing-bibliography';
import { writingExportModel } from '@/lib/evidence-writing-export';
import { buildProjectDocx, buildProjectPdf } from '@/lib/project-document-export';
import { readWritingRichDocument, writingRichText, type WritingRichDocument, type WritingRichNode } from '@/lib/writing-rich-text';

const paragraph = (text = '', bold = false): WritingRichNode => ({ type: 'paragraph', ...(text ? { content: [{ type: 'text', text, ...(bold ? { marks: [{ type: 'bold' as const }] } : {}) }] } : {}) });
const cell = (content: WritingRichNode[], header = false): WritingRichNode => ({ type: header ? 'tableHeader' : 'tableCell', content });
const row = (...cells: WritingRichNode[]): WritingRichNode => ({ type: 'tableRow', content: cells });
const table = (...rows: WritingRichNode[]): WritingRichNode => ({ type: 'table', content: rows });
const validate = (content: WritingRichNode[]): WritingRichDocument => {
  const value = readWritingRichDocument({ type: 'doc', content });
  expect(value).not.toBeNull(); return value!;
};

function parsePdf(path: string): { total: number; pages: { num: number; text: string }[]; text: string } {
  // Run the installed parser in Node rather than letting Jest transform its
  // ESM PDF.js worker. This reads the generated bytes and makes no requests.
  const source = `import { PDFParse } from 'pdf-parse';
    import { readFileSync } from 'node:fs';
    const parser = new PDFParse({ data: new Uint8Array(readFileSync(process.argv[1])), verbosity: 0 });
    try { const result = await parser.getText(); process.stdout.write(JSON.stringify(result)); }
    finally { await parser.destroy(); }`;
  return JSON.parse(execFileSync(process.execPath, ['--input-type=module', '-e', source, path], { cwd: process.cwd(), encoding: 'utf8', timeout: 30_000, maxBuffer: 8 * 1024 * 1024 }));
}

function saveArtifact(name: string, bytes: Buffer) {
  if (!process.env.WAHA_QA_ARTIFACT_DIR) return;
  mkdirSync(process.env.WAHA_QA_ARTIFACT_DIR, { recursive: true });
  writeFileSync(join(process.env.WAHA_QA_ARTIFACT_DIR, name), bytes);
}

test.each(['ar', 'en'] as const)('exports editable table cells, header semantics and a cited claim (%s)', async language => {
  const ar = language === 'ar';
  const claim = ar ? 'النتيجة محدودة بالعينة ٤٢.' : 'The result is limited to sample 42.';
  const original = validate([
    paragraph(ar ? 'قبل الجدول' : 'Before the table'),
    table(
      row(cell([paragraph(ar ? 'الدراسة' : 'Study')], true), cell([paragraph(ar ? 'النتيجة' : 'Finding')], true), cell([paragraph(ar ? 'الملاحظة' : 'Note')], true)),
      row(cell([paragraph('Smith 2024')]), cell([paragraph(claim, true), paragraph(ar ? 'مراجعة ثانية' : 'Second paragraph')]), cell([paragraph()])),
      row(cell([paragraph('<script>alert(1)</script>')]), cell([paragraph(ar ? 'المجلد 12(2), 10–18.' : 'Volume 12(2), 10–18.')]), cell([paragraph(ar ? 'هذه عينة تنسيق' : 'Formatting fixture')])),
    ),
    paragraph(ar ? 'بعد الجدول' : 'After the table'),
  ]);
  const text = writingRichText(original), claimStart = text.indexOf(claim);
  const source = { id: 'ba13fcdb-69a7-41aa-a2c9-c495917bcfa3', kind: 'reference' as const, title: 'Fixture study', text: 'Bounded original passage.', hash: 'a'.repeat(64), origin: 'user_asserted', url: null, year: 2024, bibliography: bibliographyFromReference({ authors: [{ family: 'Smith', given: 'Jane' }], publication_title: 'Fixture Journal', doi: null, citation_data: {} }) };
  const citation = attachWritingSource({ id: 'faddfe2c-78f0-4e15-a24d-df151c43f7aa', claimStart, claimEnd: claimStart + claim.length, claimText: claim, sourceKind: 'reference', sourceId: source.id, sourceHash: source.hash, quoteStart: 0, quoteEnd: source.text.length, quoteText: source.text, relation: 'contextual', note: '' }, source);
  const snapshot = JSON.stringify(original);
  const model = writingExportModel({ text, richText: original, citations: [citation] }, language);
  const folder = mkdtempSync(join(tmpdir(), 'waha-table-export-'));
  try {
    const docx = await buildProjectDocx(model), pdf = await buildProjectPdf(model);
    const path = join(folder, 'table.docx'); writeFileSync(path, docx);
    const xml = execFileSync('unzip', ['-p', path, 'word/document.xml'], { encoding: 'utf8' });
    expect((xml.match(/<w:tbl>/g) || [])).toHaveLength(1);
    expect((xml.match(/<w:tr>/g) || [])).toHaveLength(3);
    expect((xml.match(/<w:tc>/g) || [])).toHaveLength(9);
    expect((xml.match(/<w:tblHeader\b/g) || [])).toHaveLength(1);
    expect(xml).toContain('w:type="fixed"');
    expect(xml).toContain(ar ? '<w:bidiVisual/>' : '<w:bidiVisual w:val="false"/>');
    expect(xml).toContain('&lt;script&gt;alert(1)&lt;/script&gt;'); expect(xml).not.toContain('<script>');
    const citedCell = (xml.match(/<w:tc>[\s\S]*?<\/w:tc>/g) || []).find(content => content.includes('(Smith, 2024)'))!;
    expect(citedCell).toBeDefined(); expect(citedCell).toContain('<w:b/>');
    expect(citedCell.replace(/<[^>]+>/g, '').replace(/\u200e/g, '')).toContain(ar ? 'مراجعة ثانية' : 'Second paragraph');
    expect(JSON.stringify(original)).toBe(snapshot); expect(writingRichText(original)).toBe(text);
    const pdfPath = join(folder, 'table.pdf'); writeFileSync(pdfPath, pdf);
    const extracted = parsePdf(pdfPath);
    expect(extracted.total).toBeGreaterThan(0); expect(extracted.text).toContain('Smith'); expect(extracted.text).toContain('2024');
    // A three-column Arabic cell leaves too little room beside the claim.
    // The displayed CSL run must move intact rather than strand its year.
    expect(extracted.text.split(/\r?\n/u).some(line => /\(Smith,[\t ]+2024\)/u.test(line))).toBe(true);
    expect(extracted.text).toContain('12(2), 10–18');
    if (!ar) expect(extracted.text).toContain('After the table');
    saveArtifact(`writing-table-${language}.docx`, docx); saveArtifact(`writing-table-${language}.pdf`, pdf);
  } finally { rmSync(folder, { recursive: true, force: true }); }
}, 45_000);

test('a cell longer than a page continues without dropping words and repeats the leading header', async () => {
  const words = Array.from({ length: 240 }, (_, index) => `token${String(index).padStart(3, '0')}`);
  const richText = validate([table(
    row(cell([paragraph('Study header')], true), cell([paragraph('Evidence header')], true)),
    row(cell([paragraph('BEGINCELL ' + words.join(' ') + ' ENDCELL')]), cell([paragraph('OTHER_COLUMN_END')])),
    row(cell([paragraph('FINAL_ROW')]), cell([paragraph('FINAL_CELL')])),
  ), paragraph('AFTER_TABLE')]);
  const model = writingExportModel({ text: writingRichText(richText), richText, citations: [] }, 'en');
  const folder = mkdtempSync(join(tmpdir(), 'waha-table-pages-'));
  try {
    const pdf = await buildProjectPdf(model), path = join(folder, 'table.pdf'); writeFileSync(path, pdf);
    const extracted = parsePdf(path);
    expect(extracted.total).toBeGreaterThan(1);
    for (const word of words) expect(extracted.text).toContain(word);
    for (const marker of ['BEGINCELL', 'ENDCELL', 'OTHER_COLUMN_END', 'FINAL_ROW', 'FINAL_CELL', 'AFTER_TABLE']) expect(extracted.text).toContain(marker);
    const continuationPages = extracted.pages.filter(page => /token\d{3}/u.test(page.text));
    expect(continuationPages.length).toBeGreaterThan(1);
    for (const page of continuationPages) { expect(page.text).toContain('Study header'); expect(page.text).toContain('Evidence header'); }
    saveArtifact('writing-table-pagination.pdf', pdf);
  } finally { rmSync(folder, { recursive: true, force: true }); }
}, 45_000);

test('an oversized header can split across pages and still reach the body and following text', async () => {
  const header = Array.from({ length: 620 }, (_, index) => `header${String(index).padStart(3, '0')}`).join(' ');
  const richText = validate([table(row(cell([paragraph(header)], true)), row(cell([paragraph('BODY_AFTER_OVERSIZED_HEADER')]))), paragraph('AFTER_OVERSIZED_TABLE')]);
  const model = writingExportModel({ text: writingRichText(richText), richText, citations: [] }, 'en');
  const folder = mkdtempSync(join(tmpdir(), 'waha-table-header-'));
  try {
    const pdf = await buildProjectPdf(model), path = join(folder, 'table.pdf'); writeFileSync(path, pdf);
    const extracted = parsePdf(path);
    expect(extracted.total).toBeGreaterThan(1);
    expect(extracted.text).toContain('header000'); expect(extracted.text).toContain('header619');
    expect(extracted.text).toContain('BODY_AFTER_OVERSIZED_HEADER'); expect(extracted.text).toContain('AFTER_OVERSIZED_TABLE');
  } finally { rmSync(folder, { recursive: true, force: true }); }
}, 45_000);
